import assert from 'node:assert/strict';
import {workflowState,captureValidation,operationLabel} from './js/workflow-model.js';
const health={capabilities:{device_capture:{available:true},report_generation:{available:true}}};
const task={state:'partial',workflow:{can_capture:true,can_report:true}};
assert.equal(workflowState(task,health).canCapture,true);
assert.equal(workflowState(task,health).canReport,true);
assert.equal(workflowState({...task,state:'running'},health).canCapture,false);
assert.equal(workflowState(task,health,true).canReport,false);
assert.equal(workflowState(task,null).canCapture,false);
assert.equal(workflowState(null,health).canReport,false);
assert.equal(workflowState({state:'done'},health).canCapture,false);
assert.equal(workflowState({workflow:{can_capture:'true'}},health).canCapture,false);
assert.equal(workflowState({workflow:{capture_reason:'摘要不匹配'}},health).captureReason,'摘要不匹配');
const options={serial:'emulator-5560',authorized:true,permission_response:'deny',generate_report:true};
const devices=[{serial:'emulator-5560',state:'device'}];
assert.equal(captureValidation(options,devices),null);
assert.match(captureValidation({...options,authorized:false},devices),/授权/);
assert.match(captureValidation({...options,authorized:'true'},devices),/授权/);
assert.match(captureValidation({...options,serial:''},devices),/请选择/);
assert.match(captureValidation(options,[{serial:options.serial,state:'unauthorized'}]),/未在线/);
assert.match(captureValidation(options,null),/未在线/);
assert.match(captureValidation({...options,permission_response:'root'},devices),/只能/);
assert.match(captureValidation({...options,generate_report:'true'},devices),/是否/);
assert.equal(operationLabel('capture'),'设备采集');
assert.equal(operationLabel('report'),'报告生成');
assert.equal(operationLabel(undefined),'静态分析');
console.log('PASS 20 workflow assertions (offline UI eligibility and exact authorization).');
